#!/usr/bin/env python3
"""Build FitTrack Gym's data files from a checkout of openGym.

    git clone --depth 1 https://github.com/DuarteSantos8/openGym /path/to/opengym
    python3 gym/tools/import_opengym.py /path/to/opengym

Only the MIT-licensed parts of openGym are imported (see gym/THIRD_PARTY_NOTICES.md):

* exercises marked "textSource": "exercisedb", taking only the fields openGym's
  NOTICE.md lists as MIT (name, muscles, instructions) plus the classification
  fields (body part, equipment, category). openGym's own descriptions,
  muscle-map corrections and translations are AGPL and are left out.
* the body-diagram outlines in frontend/src/lib/body-paths.js, derived from
  MuscleMap by Melih Colpan (MIT).

No media is read or copied: openGym's exercise images and animations are
licensed from Gym visual for openGym only.

The script parses files as data and never executes code from the checkout.
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "data")

# Parts of the body diagram that are silhouette only, never shaded.
INERT = {"head", "hair", "neck", "hands", "feet", "knees", "ankles"}


def build_exercises(root):
    rows = []
    for path in sorted(glob.glob(os.path.join(root, "catalogue", "exercises", "*.json"))):
        with open(path, encoding="utf-8") as f:
            d = json.load(f)
        if d.get("textSource") != "exercisedb" or "name" not in d:
            continue
        row = {
            "id": d["id"],
            "n": d["name"],
            "b": d["bodyPart"],
            "e": d["equipment"],
            "t": d["target"],
            "s": d.get("secondaryMuscles", []),
            "c": d.get("category", "strength"),
            "i": d.get("instructions", []),
        }
        if d.get("hold"):
            row["h"] = 1
        if d.get("track") == "distance":
            row["d"] = 1
        rows.append(row)
    rows.sort(key=lambda r: r["n"])
    return rows


def build_body(root):
    with open(os.path.join(root, "frontend", "src", "lib", "body-paths.js"), encoding="utf-8") as f:
        src = f.read()
    marker = "export default "
    data = json.loads(src[src.index(marker) + len(marker):].strip().rstrip(";"))
    # Keep the structure, tag inert parts so the app need not know the list.
    return {"inert": sorted(INERT), "views": data}


def write_js(name, var, payload):
    path = os.path.join(OUT, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by gym/tools/import_opengym.py. Do not edit by hand.\n")
        f.write("// Source and licence: see gym/THIRD_PARTY_NOTICES.md\n")
        f.write(f"window.{var} = ")
        json.dump(payload, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    return path


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = sys.argv[1]
    os.makedirs(OUT, exist_ok=True)
    ex = build_exercises(root)
    p1 = write_js("exercises.js", "GYM_EXERCISES", ex)
    p2 = write_js("body-paths.js", "GYM_BODY", build_body(root))
    print(f"{len(ex)} exercises -> {p1}")
    print(f"body diagram -> {p2}")


if __name__ == "__main__":
    main()
